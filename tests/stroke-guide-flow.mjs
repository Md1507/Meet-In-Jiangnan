import {launchLoggedBrowser} from '../scripts/browser-logging.mjs';
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await launchLoggedBrowser(chromium,{headless:true});
try {
  const page = await browser.newPage({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:4173/?spike');
  const points = await page.evaluate(async () => {
    const {default: Writer} = await import('/node_modules/hanzi-writer/dist/index.esm.js');
    const {createStrokeGuide, pointAlong} = await import('/src/stroke-guide.ts');
    const data = await (await fetch('/hanzi/我.json')).json();
    const target = document.createElement('div'); target.id = 'guide-test'; document.body.append(target);
    const guide = createStrokeGuide(target, 300, 20); guide.setData(data); guide.setStroke(0);
    let count = 0;
    const writer = Writer.create(target, '我', {width:300,height:300,padding:20,charDataLoader:()=>data});
    await writer.quiz({onCorrectStroke:()=>{count++; guide.setStroke(count);}});
    window.guideTest = {guide,writer,getCount:()=>count,pointAlong};
    const t = Writer.getScalingTransform(300,300,20);
    return data.medians[0].map(([x,y])=>({x:t.x+x*t.scale,y:300-t.y-y*t.scale}));
  });
  const guide = page.locator('#guide-test .stroke-guide');
  assert.equal(await guide.evaluate(e=>getComputedStyle(e).pointerEvents),'none');
  const first = await guide.locator('polyline').getAttribute('points');
  const expected = points.map(p=>`${p.x},${p.y}`).join(' ');
  assert.equal(first,expected, 'overlay follows the transformed median');
  const math = await page.evaluate(()=>window.guideTest.pointAlong([[0,0],[10,0],[10,10]],.75));
  assert.deepEqual(math,{x:10,y:5,angle:90});
  const staticArrow = await guide.locator('.stroke-guide-arrow').getAttribute('transform');
  await page.waitForTimeout(100);
  assert.equal(await guide.locator('.stroke-guide-arrow').getAttribute('transform'), staticArrow, 'reduced motion keeps a static direction');
  await page.locator('#guide-test').scrollIntoViewIfNeeded();
  const box = await page.locator('#guide-test').boundingBox();
  await page.mouse.move(box.x+points[0].x,box.y+points[0].y); await page.mouse.down();
  for(const p of points.slice(1)) await page.mouse.move(box.x+p.x,box.y+p.y,{steps:4});
  await page.mouse.up();
  await page.waitForFunction(()=>window.guideTest.getCount()===1);
  assert.notEqual(await guide.locator('polyline').getAttribute('points'),first, 'next stroke replaces old guide');
  await page.evaluate(()=>window.guideTest.guide.setStroke(0));
  assert.equal(await guide.locator('polyline').getAttribute('points'),first, 'retry resets guide');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.evaluate(()=>window.guideTest.guide.setStroke(0));
  const before = await guide.locator('.stroke-guide-arrow').getAttribute('transform');
  await page.waitForFunction(previous => document.querySelector('#guide-test .stroke-guide-arrow')?.getAttribute('transform') !== previous, before);
  await page.evaluate(()=>window.guideTest.guide.hide());
  assert.equal(await guide.locator('path').count(),0, 'hiding cancels and clears the guide');
  await page.evaluate(()=>window.guideTest.guide.setStroke(1));
  await page.evaluate(()=>{window.guideTest.writer.cancelQuiz();window.guideTest.guide.dispose();});
  assert.equal(await guide.count(),0, 'close removes overlay');
  await page.evaluate(()=>window.guideTest.guide.setStroke(0));
  assert.equal(await guide.count(),0, 'late callbacks cannot restore a disposed guide');
  console.log('Stroke guide: local median, direction, pointer quiz, next stroke, retry and cleanup PASS.');
} finally { await browser.close(); }
